package vallegrande.edu.pe.model;

public class Libro {

    // ATRIBUTOS
    private int id;
    private String titulo;
    private String autor;
    private int anio;

    //CONSTRUCTOR
    public Libro(int id, String titulo, String autor, int anio){
        this.id = id;
        this.titulo = titulo;
        this.autor = autor;
        this.anio = anio;
    }



}
